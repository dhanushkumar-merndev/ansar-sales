#!/usr/bin/env node
// Generates src/lib/database.types.ts from supabase/migrations without Docker:
// applies the migrations to an in-memory PostgreSQL (PGlite) and introspects the
// public schema into the same shape that `supabase gen types typescript` emits.
// Against a live project you can instead run: pnpm db:types:remote
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const db = await PGlite.create();
await db.exec(readFileSync(join(root, "tests/db/supabase-stub.sql"), "utf8"));
for (const f of readdirSync(join(root, "supabase/migrations")).filter((f) => f.endsWith(".sql")).sort()) {
  await db.exec(readFileSync(join(root, "supabase/migrations", f), "utf8"));
}

const q = async (sql, params = []) => (await db.query(sql, params)).rows;

const enums = await q(`
  select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as values
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`);
const enumNames = new Set(enums.map((e) => e.name));

function tsType(udt, isArray = false) {
  if (isArray || udt.startsWith("_")) return `${tsType(udt.replace(/^_/, ""))}[]`;
  if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`;
  switch (udt) {
    case "int2": case "int4": case "int8": case "float4": case "float8": case "numeric": return "number";
    case "bool": return "boolean";
    case "json": case "jsonb": return "Json";
    case "void": return "undefined";
    default: return "string";
  }
}

const tables = await q(`
  select c.relname as name from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r' order by c.relname`);

const columns = await q(`
  select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
    c.column_default is not null or c.is_identity = 'YES' as has_default,
    c.is_generated = 'ALWAYS' as generated
  from information_schema.columns c
  where c.table_schema = 'public' order by c.table_name, c.column_name`);

const fks = await q(`
  select con.conname as name, cl.relname as table_name, rcl.relname as ref_table,
    array(select a.attname from unnest(con.conkey) with ordinality as u(k, i) join pg_attribute a on a.attrelid = con.conrelid and a.attnum = u.k order by u.i) as cols,
    array(select a.attname from unnest(con.confkey) with ordinality as u(k, i) join pg_attribute a on a.attrelid = con.confrelid and a.attnum = u.k order by u.i) as ref_cols,
    exists (select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique and i.indkey::int2[] @> con.conkey and array_length(i.indkey::int2[], 1) = array_length(con.conkey, 1)) as one_to_one
  from pg_constraint con
  join pg_class cl on cl.oid = con.conrelid join pg_namespace n on n.oid = cl.relnamespace
  join pg_class rcl on rcl.oid = con.confrelid join pg_namespace rn on rn.oid = rcl.relnamespace
  where con.contype = 'f' and n.nspname = 'public' and rn.nspname = 'public'
  order by con.conname`);

const fns = await q(`
  select p.proname as name, p.pronargs as nargs, p.pronargdefaults as ndefaults, p.proretset as retset,
    coalesce(p.proargnames, '{}') as argnames, coalesce(p.proargmodes::text[], '{}') as argmodes,
    array(select t.typname from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality as u(o, i) join pg_type t on t.oid = u.o order by u.i) as argtypes,
    rt.typname as rettype, rt.typtype as rettypetype
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
  where n.nspname = 'public' and rt.typname <> 'trigger'
  order by p.proname`);

const ind = (s, n) => s.split("\n").map((l) => (l ? " ".repeat(n) + l : l)).join("\n");
const tableRow = (t, mode) =>
  columns.filter((c) => c.table_name === t).map((c) => {
    const base = tsType(c.udt_name);
    const type = c.nullable ? `${base} | null` : base;
    if (mode === "Row") return `${c.column_name}: ${type}`;
    if (c.generated) return `${c.column_name}?: never`;
    const optional = mode === "Update" || c.nullable || c.has_default;
    return `${c.column_name}${optional ? "?" : ""}: ${type}`;
  }).join("\n");

let out = `// Generated by scripts/gen-db-types.mjs from supabase/migrations. Do not edit by hand.
// Regenerate with: pnpm db:types (local) or pnpm db:types:remote (linked Supabase project).

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]

export type Database = {
  __InternalSupabase: { PostgrestVersion: "13" }
  public: {
    Tables: {
`;
for (const { name } of tables) {
  const rels = fks.filter((f) => f.table_name === name).map((f) => `{
  foreignKeyName: "${f.name}"
  columns: [${f.cols.map((c) => `"${c}"`).join(", ")}]
  isOneToOne: ${f.one_to_one}
  referencedRelation: "${f.ref_table}"
  referencedColumns: [${f.ref_cols.map((c) => `"${c}"`).join(", ")}]
},`).join("\n");
  out += ind(`${name}: {
  Row: {
${ind(tableRow(name, "Row"), 4)}
  }
  Insert: {
${ind(tableRow(name, "Insert"), 4)}
  }
  Update: {
${ind(tableRow(name, "Update"), 4)}
  }
  Relationships: [${rels ? `\n${ind(rels, 4)}\n  ` : ""}]
}`, 6) + "\n";
}
out += `    }
    Views: { [_ in never]: never }
    Functions: {
`;
for (const f of fns) {
  const inArgs = [];
  const outCols = [];
  f.argtypes.forEach((t, i) => {
    const mode = f.argmodes[i] ?? "i";
    const name = f.argnames[i];
    if (mode === "i" || mode === "b") inArgs.push({ name, type: t });
    if (mode === "o" || mode === "b" || mode === "t") outCols.push({ name, type: t });
  });
  const firstDefault = inArgs.length - f.ndefaults;
  const args = inArgs.length
    ? `{\n${ind(inArgs.map((a, i) => `${a.name}${i >= firstDefault ? "?" : ""}: ${tsType(a.type)}`).join("\n"), 2)}\n}`
    : "never";
  let ret;
  if (outCols.length) ret = `{\n${ind(outCols.map((c) => `${c.name}: ${tsType(c.type)}`).join("\n"), 2)}\n}[]`;
  else if (f.rettypetype === "c") ret = `Database["public"]["Tables"]["${f.rettype}"]["Row"]`;
  else ret = tsType(f.rettype) + (f.retset ? "[]" : "");
  out += ind(`${f.name}: {\n  Args: ${ind(args, 2).trimStart()}\n  Returns: ${ind(ret, 2).trimStart()}\n}`, 6) + "\n";
}
out += `    }
    Enums: {
${enums.map((e) => `      ${e.name}: ${e.values.map((v) => `"${v}"`).join(" | ")}`).join("\n")}
    }
    CompositeTypes: { [_ in never]: never }
  }
}

type PublicSchema = Database["public"]
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"]
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"]
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"]
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T]

export const Constants = {
  public: {
    Enums: {
${enums.map((e) => `      ${e.name}: [${e.values.map((v) => `"${v}"`).join(", ")}],`).join("\n")}
    },
  },
} as const
`;

writeFileSync(join(root, "src/lib/database.types.ts"), out);
console.log(`Wrote src/lib/database.types.ts (${tables.length} tables, ${fns.length} functions, ${enums.length} enums)`);
await db.close();
